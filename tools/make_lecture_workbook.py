def 날짜로(값):
    """'2026-01-14' 같은 문자열을 진짜 날짜로 바꾼다.

    문자열로 넣으면 엑셀이 텍스트로 저장해서 날짜 비교(TODAY 등)가 안 된다.
    """
    if isinstance(값, str) and len(값) == 10 and 값[4] == "-":
        return date.fromisoformat(값)
    return 값


