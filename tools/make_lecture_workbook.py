# -*- coding: utf-8 -*-
"""강의 이력 입력용 엑셀(data/강의이력.xlsx)을 생성한다.

기존 data/lectures.json의 내용을 미리 채워넣어, 빈 표부터 시작하지 않도록 한다.
한 번 만든 뒤에는 다시 실행할 일이 거의 없다 (실행하면 입력 내용이 사라진다).
"""
import json
from pathlib import Path

from openpyxl import Workbook
from openpyxl.comments import Comment
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

저장_경로 = Path("data/강의이력.xlsx")
마지막_행 = 500          # 수식이 내다보는 범위 (행을 더 쓰려면 이 값을 늘린다)

# ── 서식 상수 ──────────────────────────────────────────────────────
글꼴 = "맑은 고딕"       # 내용이 한글이므로 한글 전용 서체를 쓴다
브랜드_그린 = "0B4D3B"
민트 = "E8F4EE"
노랑 = "FFF9DB"          # 사용자가 채워야 할 칸

제목_글꼴 = Font(name=글꼴, size=14, bold=True, color=브랜드_그린)
헤더_글꼴 = Font(name=글꼴, size=10, bold=True, color="FFFFFF")
본문_글꼴 = Font(name=글꼴, size=10)
안내_글꼴 = Font(name=글꼴, size=9, color="7A8580")
수치_글꼴 = Font(name=글꼴, size=16, bold=True, color=브랜드_그린)

헤더_채움 = PatternFill("solid", fgColor=브랜드_그린)
민트_채움 = PatternFill("solid", fgColor=민트)
노랑_채움 = PatternFill("solid", fgColor=노랑)

얇은_선 = Side(style="thin", color="D5DEDA")
테두리 = Border(left=얇은_선, right=얇은_선, top=얇은_선, bottom=얇은_선)

# ── 열 정의: (헤더, 너비, 설명(셀 메모), 노랑칠 여부) ──────────────
열_정의 = [
    ("일자",        12, "강의한 날짜. 2026-10-27 형식으로 입력하세요. 여러 날이면 시작일.", True),
    ("강의명",      34, "강의 제목. 같은 과정을 여러 번 했으면 매번 같은 이름으로 쓰세요(그래야 횟수가 집계됩니다).", True),
    ("표시기관명",  20, "홈페이지에 보일 이름. 무명 업체면 '제조업 재직자 과정'처럼 업종으로 쓰세요.", True),
    ("교육대상",    22, "실제 교육받은 조직. 예: 대성에너지 직무훈련과정. 없으면 비워두세요.", False),
    ("에이전시",    18, "경유한 에이전시. ★홈페이지에 절대 표시되지 않는 내부 기록용입니다.", False),
    ("교육시간",     9, "총 강의 시간(숫자만). 예: 8", True),
    ("수강인원",     9, "수강한 인원 수(숫자만). 예: 25  ← 이 값이 홈페이지 '누적 수강생'이 됩니다.", True),
    ("구분",        14, "대표강의 / 기관·기업 / 자체과정 중에서 고르세요.", True),
    ("홈페이지표시", 11, "Y면 홈페이지 강의 이력에 나옵니다. N이면 집계에만 반영되고 목록에는 안 나옵니다.", True),
    ("신청링크",    30, "수강 신청 페이지 주소. 있으면 홈페이지에서 클릭 가능해집니다.", False),
    ("비고",        24, "메모. '예시'로 시작하면 홈페이지 반영에서 제외됩니다.", False),
]

워크북 = Workbook()

# ═══════════════════════════════════════════════════════════════════
#  시트 1: 강의이력 (입력 표)
# ═══════════════════════════════════════════════════════════════════
이력 = 워크북.active
이력.title = "강의이력"

이력["A1"] = "강의 이력 입력표"
이력["A1"].font = 제목_글꼴
이력["A2"] = ("강의를 할 때마다 한 줄씩 추가하세요. 노란 칸은 꼭 채워야 합니다. "
              "다 적으신 뒤 Claude에게 '강의이력 업데이트해줘'라고 하면 홈페이지에 반영됩니다.")
이력["A2"].font = 안내_글꼴
이력.merge_cells("A2:K2")

헤더_행 = 4
for 번호, (헤더, 너비, 설명, _) in enumerate(열_정의, start=1):
    칸 = 이력.cell(row=헤더_행, column=번호, value=헤더)
    칸.font = 헤더_글꼴
    칸.fill = 헤더_채움
    칸.alignment = Alignment(horizontal="center", vertical="center")
    칸.border = 테두리
    칸.comment = Comment(설명, "로직플로우")
    이력.column_dimensions[get_column_letter(번호)].width = 너비
이력.row_dimensions[헤더_행].height = 24


def 행_쓰기(행번호: int, 값들: dict, 예시: bool = False) -> None:
    """한 줄을 쓰고 서식을 입힌다."""
    for 번호, (헤더, _, _, 노랑칠) in enumerate(열_정의, start=1):
        칸 = 이력.cell(row=행번호, column=번호, value=값들.get(헤더))
        칸.font = 본문_글꼴
        칸.border = 테두리
        칸.alignment = Alignment(vertical="center",
                                 horizontal="center" if 헤더 in ("일자", "교육시간", "수강인원", "구분", "홈페이지표시") else "left",
                                 wrap_text=헤더 in ("강의명", "교육대상"))
        if 헤더 == "일자":
            칸.number_format = "yyyy-mm-dd"
        if 예시:
            칸.fill = 민트_채움
        elif 노랑칠 and 값들.get(헤더) in (None, ""):
            칸.fill = 노랑_채움        # 채워야 할 빈 칸을 노랗게


# ── 예시 행 1줄 ────────────────────────────────────────────────────
행_쓰기(5, {
    "일자": "2026-10-15",
    "강의명": "AI활용 실무: 사무자동화 마스터 클래스",
    "표시기관명": "대구YMCA",
    "교육대상": "대성에너지 직무훈련과정",
    "에이전시": "",
    "교육시간": 8,
    "수강인원": 24,
    "구분": "기관·기업",
    "홈페이지표시": "Y",
    "신청링크": "",
    "비고": "예시 행 — 형식 확인 후 삭제하세요",
}, 예시=True)

# ── 기존 lectures.json 내용을 미리 채워넣기 ────────────────────────
구분_이름 = {"featured": "대표강의", "institution": "기관·기업", "own": "자체과정"}
기존 = json.loads(Path("data/lectures.json").read_text(encoding="utf-8"))

현재_행 = 6
for 그룹 in 기존["groups"]:
    for 강의 in 그룹["items"]:
        행_쓰기(현재_행, {
            "강의명": 강의.get("title"),
            "표시기관명": 강의.get("client"),
            "교육대상": 강의.get("target"),
            "에이전시": 강의.get("agency"),
            "구분": 구분_이름.get(그룹["id"], "기관·기업"),
            "홈페이지표시": "Y",
            "신청링크": 강의.get("url"),
            "비고": "기존 이력 — 일자·시간·인원을 채워주세요",
        })
        현재_행 += 1

마지막_내용_행 = 현재_행 - 1

# 빈 줄에도 미리 서식을 깔아둔다 (바로 이어서 입력할 수 있도록)
for 행 in range(현재_행, 현재_행 + 20):
    행_쓰기(행, {})

# ── 드롭다운 ───────────────────────────────────────────────────────
구분_검증 = DataValidation(type="list", formula1='"대표강의,기관·기업,자체과정"', allow_blank=True)
표시_검증 = DataValidation(type="list", formula1='"Y,N"', allow_blank=True)
이력.add_data_validation(구분_검증)
이력.add_data_validation(표시_검증)
구분_검증.add(f"H5:H{마지막_행}")
표시_검증.add(f"I5:I{마지막_행}")

이력.freeze_panes = "A5"
이력.auto_filter.ref = f"A{헤더_행}:K{마지막_내용_행}"

# ═══════════════════════════════════════════════════════════════════
#  시트 2: 집계 (수식으로 자동 계산)
# ═══════════════════════════════════════════════════════════════════
집계 = 워크북.create_sheet("집계")
집계["A1"] = "누적 집계"
집계["A1"].font = 제목_글꼴
집계["A2"] = "강의이력 시트에 입력하면 자동으로 계산됩니다. 이 시트는 직접 고치지 마세요."
집계["A2"].font = 안내_글꼴
집계.merge_cells("A2:D2")

데이터_범위 = lambda 열: f"강의이력!${열}$5:${열}${마지막_행}"

# 비고가 '예시'로 시작하는 줄은 집계에서 뺀다.
# (예시 행을 지워도 수식이 그대로 동작하도록, 범위를 자르지 않고 조건으로 거른다)
예시_제외 = f'{데이터_범위("K")},"<>예시*"'

지표들 = [
    ("누적 강의 횟수", f'=COUNTIFS({데이터_범위("B")},"<>",{예시_제외})', "회"),
    ("누적 수강생",   f'=SUMIFS({데이터_범위("G")},{예시_제외})', "명"),
    ("누적 교육시간", f'=SUMIFS({데이터_범위("F")},{예시_제외})', "시간"),
    # 중복 없는 기관 수. 예시 행의 기관명은 실제 이력에도 있는 이름을 써서
    # 예시를 지우든 두든 결과가 같다.
    ("협력 기관 수",
     f'=SUMPRODUCT(({데이터_범위("C")}<>"")/COUNTIF({데이터_범위("C")},{데이터_범위("C")}&""))', "곳"),
]

집계["A4"], 집계["B4"], 집계["C4"] = "지표", "값", "단위"
for 칸이름 in ("A4", "B4", "C4"):
    집계[칸이름].font = 헤더_글꼴
    집계[칸이름].fill = 헤더_채움
    집계[칸이름].alignment = Alignment(horizontal="center")
    집계[칸이름].border = 테두리

for 순번, (이름, 수식, 단위) in enumerate(지표들, start=5):
    집계[f"A{순번}"] = 이름
    집계[f"A{순번}"].font = 본문_글꼴
    집계[f"B{순번}"] = 수식
    집계[f"B{순번}"].font = 수치_글꼴
    집계[f"B{순번}"].number_format = "#,##0"
    집계[f"B{순번}"].fill = 민트_채움
    집계[f"C{순번}"] = 단위
    집계[f"C{순번}"].font = 안내_글꼴
    for 열 in "ABC":
        집계[f"{열}{순번}"].border = 테두리
        집계[f"{열}{순번}"].alignment = Alignment(horizontal="center" if 열 != "A" else "left",
                                                  vertical="center")
    집계.row_dimensions[순번].height = 26

# ── 연도별 집계 ────────────────────────────────────────────────────
집계["A11"] = "연도별"
집계["A11"].font = Font(name=글꼴, size=11, bold=True, color=브랜드_그린)

집계["A12"], 집계["B12"], 집계["C12"] = "연도", "강의 횟수", "수강생"
for 칸이름 in ("A12", "B12", "C12"):
    집계[칸이름].font = 헤더_글꼴
    집계[칸이름].fill = 헤더_채움
    집계[칸이름].alignment = Alignment(horizontal="center")
    집계[칸이름].border = 테두리

for 순번, 연도 in enumerate([2025, 2026, 2027, 2028], start=13):
    집계[f"A{순번}"] = 연도
    집계[f"A{순번}"].number_format = "0"
    # 일자가 비어 있으면 YEAR()가 1899를 돌려주므로 자연히 제외된다.
    # LEFT(비고,2)<>"예시" 로 예시 행을 걸러낸다.
    연도_조건 = f'(YEAR({데이터_범위("A")})=$A{순번})*(LEFT({데이터_범위("K")},2)<>"예시")'
    집계[f"B{순번}"] = f'=SUMPRODUCT({연도_조건}*({데이터_범위("B")}<>""))'
    집계[f"C{순번}"] = f'=SUMPRODUCT({연도_조건}*{데이터_범위("G")})'
    for 열 in "ABC":
        집계[f"{열}{순번}"].font = 본문_글꼴
        집계[f"{열}{순번}"].border = 테두리
        집계[f"{열}{순번}"].alignment = Alignment(horizontal="center")
        if 열 != "A":
            집계[f"{열}{순번}"].number_format = "#,##0"

집계["A18"] = ("※ '누적 강의 횟수'는 비고가 '예시'로 시작하는 줄을 빼고 셉니다. "
               "홈페이지 지표는 이 값을 그대로 가져갑니다.")
집계["A18"].font = 안내_글꼴
집계.merge_cells("A18:D18")

for 열, 너비 in zip("ABCD", (18, 14, 12, 40)):
    집계.column_dimensions[열].width = 너비

# ═══════════════════════════════════════════════════════════════════
#  시트 3: 입력안내
# ═══════════════════════════════════════════════════════════════════
안내 = 워크북.create_sheet("입력안내")
안내["A1"] = "입력 안내"
안내["A1"].font = 제목_글꼴

안내_내용 = [
    ("", ""),
    ("■ 색깔이 뜻하는 것", ""),
    ("노란 칸", "꼭 채워야 하는 항목입니다."),
    ("민트색 줄", "예시 행입니다. 형식을 확인한 뒤 삭제하세요."),
    ("", ""),
    ("■ 기관명을 어떻게 쓸지", ""),
    ("들으면 아는 곳", "실명을 씁니다. 예: KISTI, 멀티캠퍼스, NH투자증권, 대구YMCA"),
    ("에이전시를 통한 경우", "최종 교육처를 '표시기관명'에, 에이전시는 '에이전시' 칸에 적습니다. 에이전시는 홈페이지에 안 나옵니다."),
    ("둘 다 무명인 경우", "이름 대신 업종으로 씁니다. 예: 제조업 재직자 과정, 지역 중소기업 직무교육"),
    ("", "모르는 에이전시 이름은 신뢰도를 올리지 못합니다. 이름을 빼는 건 숨기는 게 아니라 읽는 사람에게 의미 있는 정보로 바꾸는 것입니다."),
    ("", ""),
    ("■ 같은 과정을 여러 번 했을 때", ""),
    ("", "할 때마다 한 줄씩 추가하세요. 강의명을 똑같이 쓰면 홈페이지 목록에는 한 줄로 합쳐지고, 횟수와 인원은 모두 더해집니다."),
    ("", ""),
    ("■ 홈페이지에 반영하는 법", ""),
    ("1단계", "이 파일에 입력하고 저장합니다."),
    ("2단계", "Claude에게 '강의이력 업데이트해줘'라고 말합니다."),
    ("3단계", "lectures.json과 stats.json이 자동으로 갱신되고, 커밋·푸시하면 사이트에 반영됩니다."),
    ("", ""),
    ("■ 주의", ""),
    ("", "헤더(4행)의 이름을 바꾸지 마세요. 자동 반영이 멈춥니다."),
    ("", "'집계' 시트는 수식이므로 직접 고치지 마세요."),
    ("", "홈페이지표시를 N으로 두면 목록에는 안 나오지만 누적 인원 집계에는 들어갑니다."),
]

for 순번, (왼쪽, 오른쪽) in enumerate(안내_내용, start=2):
    안내[f"A{순번}"] = 왼쪽
    안내[f"B{순번}"] = 오른쪽
    굵게 = 왼쪽.startswith("■")
    안내[f"A{순번}"].font = Font(name=글꼴, size=11 if 굵게 else 10,
                                 bold=굵게, color=브랜드_그린 if 굵게 else "000000")
    안내[f"B{순번}"].font = 본문_글꼴
    안내[f"B{순번}"].alignment = Alignment(wrap_text=True, vertical="top")

안내.column_dimensions["A"].width = 24
안내.column_dimensions["B"].width = 88

워크북.save(저장_경로)
